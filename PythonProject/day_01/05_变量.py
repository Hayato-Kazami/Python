"""
变量是程序中用来存储数据的容器，通常会把经常发生变化的数据存储在变量中
格式定义：变量名 = 变量的值
"""

# 定义同学的名字
name = "王麻子"
print(name)
name = "王林"
print(name)  # print打印的是变量中存储的值


# 定义同学的年龄
age=18
print(age)


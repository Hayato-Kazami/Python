"""
案例：要求输入两个小数X与y，分别输出X+y的结果和X-y的结果
"""

# 1.要求输入两个小数X与y -->键盘录入
X_str = input("请输入X的值：") # 1.5
y_str = input("请输入y的值：") # 1.1 
# 2.将str类型转为float类型
X = float(X_str)
y = float(y_str)
# 3.输出结果
print(f"{X} + {y} = {X+y}") # 1.5 + 1.1 = 2.6
print(f"{X} - {y} = {X-y}") # 1.5 - 1.1 = 0.3999999999999999
# 补充：计算机在处理浮点数的时候会丢失精准度
"""
思考1：数学计算中，判断一个数是否为偶数，使用哪个关系运算符呢？
答：使用 ==  判断 对2取余结果 是否等于 0

题目1: 从控制台随便输入一个整数，输出是否为偶数

思考2：电商项目的支付功能业务，需要判断银行卡余额是否足够，使用哪个关系运算符呢？
答：使用 >=  判断 余额 是否 大于等于 支付金额

题目2: 假如银行卡余额为500, 从控制台随便输入一个要支付的金额, 输出是否充足
"""

# 题目1：判断输入的整数是否为偶数
# 1. 输入整数并转换类型
num = int(input("请输入一个整数："))
# 2. 判断偶数：对2取余等于0 就是偶数（== 关系运算符）
result = num % 2 == 0
# 3. 输出判断结果
print(f"{num}是否为偶数：{result}")

# 题目2：判断余额是否足够支付
# 1. 输入支付金额并转为浮点数
prepare_pay_money = float(input("请输入要支付的金额："))
# 2. 判断余额充足：余额500 >= 支付金额（>= 关系运算符）
is_success = 500 >= prepare_pay_money
# 3. 输出结果
print(f"银行卡余额是否满足支付：{is_success}")
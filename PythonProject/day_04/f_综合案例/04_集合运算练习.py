"""
集合运算练习
任务描述：set_a = {11,22,33,44,55}  set_b = {33,44,55,66,77}
编程分别输出：
1. 两个集合的交集
2. 两个集合的并集
3. set_a 独有的元素（差集）
4. 只在其中一个集合出现的元素（对称差集）
"""
set_a = {11, 22, 33, 44, 55}
set_b = {33, 44, 55, 66, 77}

# 1. 交集: 两个集合都有的元素
print(f"交集: {set_a & set_b}")

# 2. 并集: 两个集合所有元素(自动去重)
print(f"并集: {set_a | set_b}")

# 3. set_a 独有的元素（差集）
print(f"set_a 独有的元素(差集): {set_a - set_b}")

# 4. 只在其中一个集合出现的元素（对称差集）
print(f"对称差集: {set_a ^ set_b}")

"""
列表基础操作
列表：lst = [12, 23, 34, 45, 56]
1. 在末尾添加 67
2. 删除索引为 2 的元素
3. 修改索引 0 为 10
4. 输出最终列表
"""
lst = [12, 23, 34, 45, 56]
print(f"原始列表: {lst}")

# 1. 在末尾添加 67
lst.append(67)
print(f"添加 67 后: {lst}")

# 2. 删除索引为 2 的元素（删除元素 34）
lst.pop(2)
print(f"删除索引 2 后: {lst}")

# 3. 修改索引 0 为 10
lst[0] = 10
print(f"修改索引 0 后: {lst}")

# 4. 输出最终列表
print(f"最终列表: {lst}")

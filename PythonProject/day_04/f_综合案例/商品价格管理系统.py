"""
商品价格管理系统（进阶题）
要求：
1. 创建字典，内置 5 种商品及价格
2. 输入商品名称，查询价格；不存在则提示未找到
3. 输入新商品名与价格，存在则修改，不存在则添加
4. 遍历输出所有商品名称与价格，格式对齐美观
"""
# 1. 创建字典，内置 5 种商品及价格
goods = {
    "苹果": 5,
    "香蕉": 3,
    "橙子": 4,
    "西瓜": 2,
    "葡萄": 8
}

# 2. 输入商品名称，查询价格；不存在则提示未找到
name = input("请输入要查询的商品名：")
if name in goods:
    print(f"{name} 的价格为：{goods[name]} 元")
else:
    print("未找到该商品")

# 3. 输入新商品名与价格，存在则修改，不存在则添加
new_name = input("请输入要添加/修改的商品名：")
new_price = int(input("请输入价格："))

# 直接赋值：存在则覆盖，不存在则新增
goods[new_name] = new_price
print(f"商品 '{new_name}' 已更新！")

# 4. 遍历输出所有商品名称与价格，格式对齐美观
print("\n" + "=" * 30)
print(f"{'商品名称':<10} {'价格(元)':>8}")
print("-" * 30)
for name, price in goods.items():
    print(f"{name:<10} {price:>8}")
print("=" * 30)

"""
默认参数（缺省参数）：定义函数时，直接给形参设置默认值。
- 调用函数时：若不传该实参，自动使用默认值；
- 若手动传入实参，则覆盖默认值。
注意：带有默认值的参数，必须写在参数列表最右侧，不能前置。
"""

# 定义函数
def print_info(name, age, address="武汉"):
    print(f"我是:{name},我今年{age}岁了,我现在住在{address}")

# 错误示范：默认参数不能放在无默认参数前面
# def print_info(name, address="武汉", age):
#     print(f"我是:{name},我今年{age}岁了,我现在住在{address}")

# 调用函数
# 传入全部实参，覆盖默认值
print_info("张三", 18, "北京")

# 省略默认参数对应实参，自动使用预设默认值
print_info("张三", 18)
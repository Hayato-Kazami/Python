# ===================== 常用内置函数=====================
# 1. abs()：求数字的绝对值
print(abs(-8))  # 输出：8

# 2. bin()：将整数转为 0b 开头的二进制字符串
print(bin(10))  # 输出：'0b1010'

# 3. chr()：根据 Unicode 编码返回对应字符
print(chr(65))  # 输出：'A'

# 4. hex()：将整数转为 0x 开头的十六进制字符串
print(hex(15))  # 输出：'0xf'

# 5. len()：获取字符串、列表等的长度
print(len("python"))  # 输出：6

# 6. max()：获取一组数据中的最大值
print(max(12, 56, 33))  # 输出：56

# 7. min()：获取一组数据中的最小值
print(min(12, 56, 33))  # 输出：12

# 8. oct()：将整数转为 0o 开头的八进制字符串
print(oct(9))  # 输出：'0o11'

# 9. ord()：获取字符对应的 Unicode 编码
print(ord('A'))  # 输出：65

# 10. pow()：幂运算，pow(底数, 指数)
print(pow(2, 3))  # 输出：8

# 11. range()：生成 1~5 的整数序列，常用于循环
# 13. sum()：对列表、元组等序列求和
print(sum([1, 2, 3]))  # 输出：6

for i in range(1, 6):
    print(i, end=" ")  # 输出：1 2 3 4 5
print()

# 12. round()：四舍五入，保留指定位小数
print(round(3.1415, 2))  # 输出：3.14

# 14. type()：查看数据的类型
print(type(10))  # 输出：<class 'int'>